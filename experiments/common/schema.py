"""
Shared result-record schema + helpers.

Every row (real or synthetic) emitted by this project matches exactly:

  run_id, vector, transport, sdk, load_level, concurrency, mitigation,
  peak_rss_mb, mean_cpu_pct, lat_p50_ms, lat_p95_ms, lat_p99_ms, error_rate,
  time_to_oom_s, recovery_s, amplification, ts_start, ts_end, is_synthetic

`is_synthetic=False` rows come from an actual subprocess run measured with
common/sampler.py. `is_synthetic=True` rows are generated by
common/synth_model.py and are ALWAYS anchored to a real row via
`anchor_run_id` (extra, non-schema field kept for traceability) plus
`notes` describing the extrapolation. Never treat a synthetic row as if it
were observed.
"""
from __future__ import annotations

import json
import os
import uuid
from dataclasses import dataclass, asdict, field
from typing import Optional

SCHEMA_FIELDS = [
    "run_id", "vector", "transport", "sdk", "load_level", "concurrency",
    "mitigation", "peak_rss_mb", "mean_cpu_pct", "lat_p50_ms", "lat_p95_ms",
    "lat_p99_ms", "error_rate", "time_to_oom_s", "recovery_s", "amplification",
    "ts_start", "ts_end", "is_synthetic",
]


@dataclass
class Record:
    vector: str
    transport: str
    sdk: str
    load_level: int
    concurrency: int
    mitigation: bool
    peak_rss_mb: float
    mean_cpu_pct: float
    lat_p50_ms: float
    lat_p95_ms: float
    lat_p99_ms: float
    error_rate: float
    ts_start: float
    ts_end: float
    is_synthetic: bool
    time_to_oom_s: Optional[float] = None
    recovery_s: Optional[float] = None
    amplification: Optional[float] = None
    run_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    # extra traceability fields (not part of the locked schema, but kept
    # because they cost nothing and make the synthetic rows auditable)
    anchor_run_id: Optional[str] = None
    notes: Optional[str] = None
    # replication traceability (P1.1): rep_index groups repeated real runs of
    # the SAME cell; cell_id is the shared key
    # (vector x transport x sdk x load x concurrency x mitigation). A negative
    # rep_index marks a discarded warm-up rep. These are non-schema fields, in
    # the same spirit as anchor_run_id/notes.
    rep_index: Optional[int] = None
    cell_id: Optional[str] = None
    # raw per-request benign-probe latencies (ms), stored so Figure 3 can be a
    # TRUE empirical CDF aggregated across reps rather than a 3-point (p50/p95/
    # p99) reconstruction (P3.2). Non-schema field, like notes.
    benign_latencies_ms: Optional[list] = None

    def to_dict(self):
        d = asdict(self)
        return d


def percentiles(values: list[float]) -> tuple[float, float, float]:
    if not values:
        return 0.0, 0.0, 0.0
    s = sorted(values)
    n = len(s)

    def pct(p):
        if n == 1:
            return s[0]
        k = (n - 1) * p
        f = int(k)
        c = min(f + 1, n - 1)
        if f == c:
            return s[f]
        return s[f] + (s[c] - s[f]) * (k - f)

    return pct(0.50), pct(0.95), pct(0.99)


def write_records(records: list[Record], path: str):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump([r.to_dict() for r in records], fh, indent=2)
    print(f"wrote {len(records)} record(s) -> {path}")
